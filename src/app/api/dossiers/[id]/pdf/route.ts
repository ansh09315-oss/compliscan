import { NextResponse } from 'next/server';
import prisma from '@/lib/db';
import { authenticateRequest, authorizeRole } from '@/lib/auth';
import { escapeHtml, sanitizeSlug } from '@/lib/sanitize';

export const dynamic = 'force-dynamic';

export async function GET(
  request: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  // 1. Server Session Authentication & Role Verification
  const authPayload = authenticateRequest(request);
  if (!authPayload) {
    return NextResponse.json(
      { success: false, error: 'Unauthorized: Active inspector session required to access legal inspection reports.' },
      { status: 401 }
    );
  }

  if (!authorizeRole(authPayload, ['ADMIN', 'SUPERVISOR', 'INSPECTOR'])) {
    return NextResponse.json(
      { success: false, error: 'Forbidden: Insufficient regulatory authority.' },
      { status: 403 }
    );
  }

  const { id } = await params;
  const safeId = sanitizeSlug(id);

  if (!safeId) {
    return NextResponse.json({ success: false, error: 'Invalid dossier identifier.' }, { status: 400 });
  }

  // 2. Fetch dossier with linked inspector and violations
  const dossier = await prisma.inspectionDossier.findFirst({
    where: {
      OR: [
        { id: safeId },
        { dossierReferenceCode: safeId },
      ],
    },
    include: {
      inspector: true,
      violations: true,
    },
  });

  if (!dossier) {
    return NextResponse.json(
      { success: false, error: 'Dossier not found or record has been archived.' },
      { status: 404 }
    );
  }

  // 3. Anti-BOLA / IDOR Verification:
  // Inspectors can only access reports they authored; Supervisors and Admins can view any jurisdiction report
  if (authPayload.role === 'INSPECTOR' && dossier.inspectorId !== authPayload.userId) {
    return NextResponse.json(
      { success: false, error: 'Forbidden: You do not have permission to inspect records generated by another officer.' },
      { status: 403 }
    );
  }

  const encodedId = escapeHtml(dossier.dossierReferenceCode);
  const productName = escapeHtml(dossier.productName || 'Unspecified Product');
  const brandName = escapeHtml(dossier.brandName || 'Unspecified Brand');
  const verdict = escapeHtml(dossier.verdict || 'PENDING');
  const inspectorName = escapeHtml(dossier.inspector?.fullName || authPayload.fullName || 'Authorized Officer');
  const badgeNumber = escapeHtml(dossier.inspector?.badgeNumber || authPayload.badgeNumber || 'OFFICER-GOV');
  const district = escapeHtml(dossier.inspector?.assignedDistrict || authPayload.assignedDistrict || 'Central Jurisdiction');
  const inspectionDate = new Date(dossier.inspectionTimestamp).toLocaleDateString('en-IN', {
    dateStyle: 'long',
  });

  // Return a sanitized HTML report with safe content-security-policy headers
  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>Inspection Report - ${encodedId}</title>
  <style>
    body { font-family: 'Times New Roman', serif; max-width: 800px; margin: 0 auto; padding: 40px; color: #111; line-height: 1.5; }
    h1 { text-align: center; font-size: 18px; border-bottom: 2px solid #0B2545; padding-bottom: 12px; margin-bottom: 4px; }
    .header { text-align: center; margin-bottom: 24px; }
    .meta-table { width: 100%; border-collapse: collapse; margin-bottom: 20px; font-size: 13px; }
    .meta-table td { padding: 6px 8px; border: 1px solid #D1D5DB; }
    .meta-table td.label { font-weight: bold; background: #F3F4F6; width: 35%; }
    .section { margin-top: 24px; }
    .section h2 { font-size: 14px; background: #0B2545; color: #fff; padding: 6px 12px; margin-bottom: 10px; }
    .violations-table { width: 100%; border-collapse: collapse; font-size: 12px; }
    .violations-table th, .violations-table td { padding: 8px; border: 1px solid #D1D5DB; text-align: left; }
    .violations-table th { background: #E5E7EB; }
    .certificate { border: 2px solid #D4AF37; padding: 16px; margin-top: 30px; background: #FAFAF5; }
    .badge { display: inline-block; padding: 3px 8px; font-size: 11px; font-weight: bold; border-radius: 4px; }
    .badge-pass { background: #DCFCE7; color: #166534; }
    .badge-fail { background: #FEE2E2; color: #991B1B; }
    .badge-review { background: #FEF3C7; color: #92400E; }
  </style>
</head>
<body>
  <div class="header">
    <p style="font-size: 12px; letter-spacing: 2px; margin: 0;">GOVERNMENT OF INDIA</p>
    <p style="font-size: 11px; color: #555; margin: 2px 0 10px 0;">DEPARTMENT OF CONSUMER AFFAIRS — LEGAL METROLOGY DIVISION</p>
    <h1>STATUTORY PACKAGED COMMODITIES INSPECTION REPORT</h1>
    <p style="margin-top: 6px;">Dossier Reference: <strong>${encodedId}</strong></p>
  </div>

  <table class="meta-table">
    <tr>
      <td class="label">Product Inspected</td>
      <td>${productName} (${brandName})</td>
    </tr>
    <tr>
      <td class="label">Inspection Date & Jurisdiction</td>
      <td>${inspectionDate} | District: ${district}</td>
    </tr>
    <tr>
      <td class="label">Investigating Inspector</td>
      <td>${inspectorName} (Badge #${badgeNumber})</td>
    </tr>
    <tr>
      <td class="label">Declared Net Quantity & MRP</td>
      <td>${dossier.declaredNetQuantity} ${escapeHtml(dossier.declaredNetUnit || 'g')} | ₹${dossier.declaredMrp}</td>
    </tr>
    <tr>
      <td class="label">Compliance Score & Verdict</td>
      <td>
        <strong>${dossier.complianceScore.toFixed(1)}%</strong> — 
        <span class="badge ${verdict === 'COMPLIANT' ? 'badge-pass' : verdict === 'NON_COMPLIANT' ? 'badge-fail' : 'badge-review'}">
          ${verdict}
        </span>
      </td>
    </tr>
    <tr>
      <td class="label">Section 63 Evidentiary SHA256</td>
      <td style="font-family: monospace; font-size: 11px; word-break: break-all;">${escapeHtml(dossier.masterSha256Hash)}</td>
    </tr>
  </table>

  <div class="section">
    <h2>STATUTORY VIOLATION FINDINGS (${dossier.violations.length})</h2>
    ${
      dossier.violations.length === 0
        ? '<p style="font-size: 13px; color: #166534; padding: 8px;">No statutory violations detected under Legal Metrology (Packaged Commodities) Rules, 2011.</p>'
        : `<table class="violations-table">
            <thead>
              <tr>
                <th>Rule Reference</th>
                <th>Violation Title</th>
                <th>Severity</th>
                <th>Required vs Detected</th>
              </tr>
            </thead>
            <tbody>
              ${dossier.violations
                .map(
                  (v) => `<tr>
                    <td><strong>${escapeHtml(v.statutoryRuleRef)}</strong></td>
                    <td>${escapeHtml(v.violationTitle)}</td>
                    <td>${escapeHtml(v.severity)}</td>
                    <td>Req: ${escapeHtml(v.requiredValue || 'N/A')} | Det: ${escapeHtml(v.detectedValue || 'N/A')}</td>
                  </tr>`
                )
                .join('')}
            </tbody>
          </table>`
    }
  </div>

  <div class="certificate">
    <h3 style="color: #92400E; margin-top: 0;">Section 63 — Bharatiya Sakshya Adhiniyam, 2023 (BSA)</h3>
    <p style="font-size: 12px; margin-bottom: 0;">
      <strong>Digital Evidence Certificate:</strong> This electronic record was cryptographically signed and sealed under 
      the active authority of Inspector <strong>${inspectorName} (${badgeNumber})</strong>. Meets all conditions of Section 63(4) 
      for judicial admissibility in enforcement proceedings.
    </p>
  </div>
</body>
</html>`;

  return new NextResponse(html, {
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'X-Content-Type-Options': 'nosniff',
      'X-Frame-Options': 'DENY',
      'Content-Security-Policy': "default-src 'none'; style-src 'unsafe-inline';",
    },
  });
}
